const ai = require("../config/gemini");

let currentQuestion = "";
let interviewStarted = false;


// ==========================================
// 1. START INTERVIEW
// ==========================================

const interviewController = async (req, res) => {
  try {
    const { role, experienceLevel, interviewType } = req.body;

    const response = await ai.models.generateContent({
      model: "gemini-3.5-flash-lite",

      contents: `
You are an AI Interview Coach.

Your job is to conduct a realistic professional interview.

Candidate information:

Role: ${role}
Experience Level: ${experienceLevel}
Interview Type: ${interviewType}

Instructions:

1. The candidate has already provided their role, experience level and interview type.
2. Do NOT ask the candidate for these details again.
3. Start the interview by asking exactly ONE question.
4. Generate the question dynamically based on the candidate's role, experience level and interview type.
5. Do not use a fixed question list.
6. Start with an appropriate difficulty level.
7. Do not provide the answer.
8. Do not provide feedback yet.
9. Return ONLY the interview question.

Generate the first interview question now.
`
    });

    currentQuestion = response.text;
    interviewStarted = true;

    console.log("Question:", currentQuestion);

    return res.status(200).json({
      question: currentQuestion
    });

  } catch (error) {
    console.error(error);

    return res.status(500).json({
      message: "Failed to start interview"
    });
  }
};


// ==========================================
// 2. CHECK ANSWER + GENERATE NEXT QUESTION
// ==========================================

const startMessaging = async (req, res) => {
  try {

    const { answer } = req.body;

    if (!answer) {
      return res.status(400).json({
        message: "Answer is required"
      });
    }

    if (!interviewStarted || !currentQuestion) {
      return res.status(400).json({
        message: "Interview has not been started"
      });
    }


    const response = await ai.models.generateContent({

      model: "gemini-3.5-flash-lite",

      contents: `
You are an AI Interview Coach.

You are conducting an interview.

The current interview question is:

${currentQuestion}


The candidate's answer is:

${answer}


Analyze the candidate's answer carefully.

Evaluate the answer using these points:

1. Understanding
2. Correctness
3. Relevance
4. Completeness
5. Clarity
6. Communication
7. Confidence
8. Depth of knowledge

For every point:

- Give a rating from 1 to 10.
- Give a short explanation for the rating.

Then provide:

- Overall rating from 1 to 10
- What the candidate did well
- What the candidate should improve
- A better way the candidate could have answered
- A short coaching tip

After the evaluation, generate EXACTLY ONE next interview question.

The next question should be based on:
- The candidate's role
- The current question
- The candidate's answer
- The candidate's performance

If the candidate gave a weak answer, ask a simpler follow-up question.

If the candidate gave a strong answer, gradually increase the difficulty.

Do not ask multiple questions.

Return the response in this exact structure:

EVALUATION

Understanding: X/10
Explanation: ...

Correctness: X/10
Explanation: ...

Relevance: X/10
Explanation: ...

Completeness: X/10
Explanation: ...

Clarity: X/10
Explanation: ...

Communication: X/10
Explanation: ...

Confidence: X/10
Explanation: ...

Depth of Knowledge: X/10
Explanation: ...

Overall Rating: X/10

What You Did Well:
...

What You Should Improve:
...

Better Answer:
...

Coaching Tip:
...

NEXT QUESTION:
...
`
    });


    const result = response.text;

    console.log(result);


    // Find the next question generated by Gemini
    const nextQuestionPart = result.split("NEXT QUESTION:")[1];

    if (nextQuestionPart) {
      currentQuestion = nextQuestionPart.trim();
    }


    return res.status(200).json({
      evaluation: result,
      nextQuestion: currentQuestion
    });

  } catch (error) {

    console.error(error);

    return res.status(500).json({
      message: "Failed to evaluate answer"
    });
  }
};


module.exports = {
  interviewController,
  startMessaging
};